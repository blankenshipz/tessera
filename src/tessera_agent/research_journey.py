"""Durable orchestration, with authenticated ports and no synthetic production defaults."""

import hashlib
import re

from .research_consumer_store import ConsumerBlocked, canonical

_ID = re.compile(r"[A-Za-z0-9][A-Za-z0-9_.:-]{0,159}\Z")


class ResearchJourney:
    """One bounded planner/critic workflow, advancing at most one stage per poll.

    approvals is an authenticated backend reader, not model text or config booleans.
    It returns immutable IDs/exact grant commands/current human review records.
    output_pipeline registers/captures continuation output with real registry/MCP
    calls; it never supplies invented generated bytes. Both production adapters
    remain explicit required ports until their cross-lane contracts are installed.
    """

    def __init__(
        self,
        journey_id,
        planner,
        critic,
        *,
        approvals,
        output_pipeline,
        initial_prompts,
        critic_transport,
    ):
        if not isinstance(journey_id, str) or not _ID.fullmatch(journey_id):
            raise ConsumerBlocked("invalid_journey_id")
        if planner.kind != "planner_proposal" or critic.kind != "critic_review":
            raise ConsumerBlocked("journey_roles_changed")
        if planner.binding["credential_id"] == critic.binding["credential_id"]:
            raise ConsumerBlocked("journey_requires_separate_principals")
        if planner.binding["context_id"] == critic.binding["context_id"]:
            raise ConsumerBlocked("journey_requires_independent_critic_context")
        if planner.binding["project_id"] != critic.binding["project_id"]:
            raise ConsumerBlocked("journey_project_changed")
        self.id, self.planner, self.critic = journey_id, planner, critic
        self.store = planner.store
        self.approvals, self.output_pipeline = approvals, output_pipeline
        self.initial_prompts, self.critic_transport = initial_prompts, critic_transport
        self.store.bind_journey(
            journey_id,
            {
                "planner_run": planner.run_id,
                "critic_run": critic.run_id,
                "planner_session": planner.binding["session_id"],
                "critic_session": critic.binding["session_id"],
                "planner_binding": hashlib.sha256(canonical(planner.binding).encode()).hexdigest(),
                "critic_binding": hashlib.sha256(canonical(critic.binding).encode()).hexdigest(),
            },
        )

    def ref(self, name, value=None):
        if value is not None and name.endswith("_id"):
            if not isinstance(value, str) or not _ID.fullmatch(value):
                raise ConsumerBlocked("invalid_journey_reference")
        return self.store.reference(self.id, name, value)

    def stage(self, value):
        self.store.journey_stage(self.id, value)

    def stop(self):
        # Local stop intent commits before interrupt or backend cancellation.
        self.ref("stop_requested", True)
        self._halt_roles("stop_requested")

    def _halt_roles(self, reason):
        for consumer in (self.planner, self.critic):
            consumer.store.runtime.stop(consumer.run_id)
            consumer.supervisor.halt(consumer.store.runtime.get(consumer.run_id), reason)

    def _poll(self):
        # Current state comes from authenticated backend reads, never a generated
        # proposal's approval claim. Ports must enforce issuer/tenant/subject pins.
        snapshot = self.approvals.poll(self.id)
        if not isinstance(snapshot, dict) or snapshot.get("journey_id") != self.id:
            raise ConsumerBlocked("authenticated_journey_poll_unknown")
        allowed = {
            "journey_id",
            "control_state",
            "review_state",
            "review_id",
            "review_subject_id",
            "approved_task_id",
            "planner_author_disclosure_id",
            "critic_author_disclosure_id",
            "planner_review_disclosure_id",
            "transport_authority",
            "commands",
        }
        if set(snapshot) - allowed:
            raise ConsumerBlocked("unsupported_authenticated_journey_poll")
        for key, value in snapshot.items():
            if key.endswith("_id") and (not isinstance(value, str) or not _ID.fullmatch(value)):
                raise ConsumerBlocked("invalid_authenticated_poll_reference")
        if snapshot.get("control_state", "continue") not in {"continue", "cancel", "revoke"}:
            raise ConsumerBlocked("unknown_authenticated_control_state")
        if snapshot.get("review_state", "pending") not in {"pending", "approved", "rejected"}:
            raise ConsumerBlocked("unknown_authenticated_review_state")
        if "transport_authority" in snapshot:
            from tessera_control.agent_authority_models import AgentAuthorityBinding

            authority = snapshot["transport_authority"]
            if (
                not isinstance(authority, dict)
                or set(authority) != {"grant_id", "revision", "epoch", "binding"}
                or not isinstance(authority["grant_id"], str)
                or not _ID.fullmatch(authority["grant_id"])
                or any(
                    type(authority[k]) is not int or authority[k] < 1 for k in ("revision", "epoch")
                )
            ):
                raise ConsumerBlocked("transport_authority_reference_invalid")
            binding = AgentAuthorityBinding.model_validate(authority["binding"]).model_dump(
                mode="json"
            )
            if any(isinstance(v, str) and not _ID.fullmatch(v) for v in binding.values()):
                raise ConsumerBlocked("transport_authority_reference_invalid")
        if "commands" in snapshot:
            from tessera_mcp.mcp_workflow import Consume

            commands = snapshot["commands"]
            if not isinstance(commands, dict) or set(commands) - {
                "admit",
                "dispatch",
                "status",
                "cancel",
            }:
                raise ConsumerBlocked("unknown_authenticated_command")
            for command in commands.values():
                if (
                    not isinstance(command, dict)
                    or set(command) != {"grant_id", "payload"}
                    or not isinstance(command["grant_id"], str)
                    or not _ID.fullmatch(command["grant_id"])
                ):
                    raise ConsumerBlocked("unknown_authenticated_command")
                parsed = Consume.model_validate(command["payload"]).model_dump(mode="json")
                for item in [parsed["model"], *parsed["command"].values()]:
                    if isinstance(item, str) and not re.fullmatch(
                        r"[A-Za-z0-9][A-Za-z0-9_.:/-]{0,199}", item
                    ):
                        raise ConsumerBlocked("invalid_authenticated_command_reference")
        return snapshot

    def advance(self):
        state = self.store.journey(self.id)["stage"]
        if state in {"completed", "rejected", "canceled", "revoked", "stopped", "failed"}:
            return self.receipt()
        snapshot = self._poll()
        # A stop may still need separately granted experiment cancellation. No
        # expired reasoning grant is used to obtain renewed execution authority.
        if (
            state == "cancel_requested"
            or self.ref("stop_requested")
            or snapshot.get("control_state") in {"cancel", "revoke"}
        ):
            reason = self.ref("termination_control")
            if reason is None:
                reason = (
                    "stopped"
                    if self.ref("stop_requested")
                    else ("canceled" if snapshot["control_state"] == "cancel" else "revoked")
                )
                self.ref("termination_control", reason)
                self._halt_roles(reason)
            if self.ref("attempt_id") and not self.ref("cancel_result"):
                self._cancel(snapshot)
                self.stage("cancel_requested")
                return self.receipt()
            if self.ref("attempt_id"):
                observed = self.approvals.read_cancel_status(self.id, self.ref("attempt_id"))
                if (
                    not isinstance(observed, dict)
                    or set(observed) != {"attempt_id", "status"}
                    or observed["attempt_id"] != self.ref("attempt_id")
                ):
                    raise ConsumerBlocked("cancel_status_unknown")
                if observed["status"] not in {"canceled", "succeeded", "failed"}:
                    self.stage("cancel_requested")
                    return self.receipt()
                self.ref("experiment_terminal_status", observed["status"])
            self.stage(reason)
            return self.receipt()
        if snapshot.get("review_state") == "rejected":
            if (
                not snapshot.get("review_id")
                or not self.ref("proposal_id")
                or snapshot.get("review_subject_id") != self.ref("proposal_id")
            ):
                raise ConsumerBlocked("human_review_record_required")
            if self.ref("attempt_id"):
                self.ref("termination_control", "rejected")
                self._cancel(snapshot)
                self.stage("cancel_requested")
                return self.receipt()
            self.ref("rejection_review_id", snapshot["review_id"])
            self.stage("rejected")
            return self.receipt()
        if state == "planner":
            result = self.planner.tick(self.initial_prompts.read("planner"))
            if result["reasoning_state"] in {"failed", "stop_acknowledged", "stop_unknown"}:
                self.stage("failed")
            elif result["output_id"]:
                self.ref("planner_initial_output", result["output_id"])
                self.stage("planner_disclosure")
        elif state == "planner_disclosure":
            disclosure = snapshot.get("planner_author_disclosure_id")
            if disclosure:
                self.planner.capture(disclosure)
                self.ref("planner_author_disclosure_id", disclosure)
                self.stage("critic")
        elif state == "critic":
            # Critic's human-curated independent role context must already bind
            # the actual disclosed planner output; no context self-disclosure.
            if self.critic.store.runtime.effect(self.critic.run_id, "prompt") is not None:
                # A prior prompt intent (including uncertainty) owns this input.
                # Poll that same session; never re-admit a newer human record or
                # render a fresh model prompt while recovering the operation.
                result = self.critic.tick()
            else:
                self.initial_prompts.verify_critic_input(self.ref("planner_initial_output"))
                result = self.critic.tick(self.initial_prompts.read("critic"))
            if result["reasoning_state"] in {"failed", "stop_acknowledged", "stop_unknown"}:
                self.stage("failed")
            elif result["output_id"]:
                self.ref("critic_output", result["output_id"])
                self.stage("critic_disclosure")
        elif state == "critic_disclosure":
            disclosure = snapshot.get("critic_author_disclosure_id")
            if disclosure:
                coverage = self.critic.capture(disclosure)
                pins = self.critic_transport.read_registered_pins(
                    self.ref("critic_output"), snapshot, coverage
                )
                from .research_peer import validate_generated

                pins = validate_generated(pins)
                if not {"capture_record_id", "capture_sequence"} <= set(pins):
                    raise ConsumerBlocked("critic_capture_ack_required")
                self.ref("critic_generated_pins", pins)
                self.ref("transport_authority", snapshot["transport_authority"])
                self.stage("peer_delivery")
        elif state == "peer_delivery":
            task = self.critic.deliver_critic(
                self.ref("critic_generated_pins"), self.ref("transport_authority")
            )
            self.ref("peer_task_id", task)
            self.stage("planner_consume")
        elif state == "planner_consume":
            self.planner.consume_critic(
                self.ref("peer_task_id"),
                self.ref("critic_generated_pins"),
                self.ref("transport_authority"),
            )
            self.stage("planner_continue")
        elif state == "planner_continue":
            self._continue_planner()
        elif state == "planner_continuation_running":
            row = self.planner.supervisor.tick(self.planner.run_id)
            if row["state"] == "completed":
                reference = self.output_pipeline.register_and_capture(
                    self.planner,
                    phase="critic_response",
                    source_sequence=2,
                    prompt_message_id=self.ref("continuation_message_id"),
                    author_disclosure_id=snapshot.get("planner_review_disclosure_id"),
                )
                if (
                    not isinstance(reference, dict)
                    or set(reference)
                    != {
                        "output_id",
                        "source_id",
                        "source_sequence",
                        "output_digest",
                        "author_disclosure_id",
                    }
                    or type(reference["source_sequence"]) is not int
                    or reference["source_sequence"] != 2
                    or not isinstance(reference["output_digest"], str)
                    or not re.fullmatch(r"[a-f0-9]{64}", reference["output_digest"])
                    or any(
                        not isinstance(reference[k], str) or not _ID.fullmatch(reference[k])
                        for k in ("output_id", "source_id", "author_disclosure_id")
                    )
                ):
                    raise ConsumerBlocked("continuation_registered_reference_invalid")
                self.ref("planner_review_output", reference)
                self.stage("submit_review_proposal")
            elif row["state"] in {"failed", "stop_acknowledged", "stop_unknown"}:
                self.stage("failed")
        elif state == "submit_review_proposal":
            proposal = self.output_pipeline.propose_registered(
                self.planner, self.ref("planner_review_output")
            )
            self.ref("proposal_id", proposal["id"])
            self.stage("human_review")
        elif state == "human_review":
            if snapshot.get("review_state") == "approved":
                self._accepted(snapshot)
                self.stage("admit")
        elif state == "admit":
            result = self._consume("admit", snapshot)
            self.ref("admit_consumption_id", result["consumption_id"])
            self.ref("attempt_id", result["result_id"])
            self.stage("dispatch")
        elif state == "dispatch":
            result = self._consume("dispatch", snapshot)
            self.ref("dispatch_consumption_id", result["consumption_id"])
            if result["operation_id"] is not None:
                self.ref("operation_id", result["operation_id"])
            self.stage("experiment_running")
        elif state == "experiment_running":
            self.planner.fence()
            self._observe_experiment(snapshot)
        elif state == "record_observation":
            self.output_pipeline.observe_registered_experiment(self.planner, self.ref("attempt_id"))
            self.stage("notebook")
        elif state == "notebook":
            # Authorized read/export; do not persist response bytes in this journal.
            self.planner.notebook()
            self.output_pipeline.export_notebook(self.planner)
            self.stage("completed")
        else:
            raise ConsumerBlocked("unsupported_journey_stage")
        return self.receipt()

    def _continue_planner(self):
        self.planner.fence()
        runtime = self.planner.store.runtime.get(self.planner.run_id)
        if runtime["state"] != "completed":
            raise ConsumerBlocked("planner_initial_session_not_complete")
        boundary = "planner_critic_response"
        prior = self.planner.store.runtime.effect(self.planner.run_id, boundary)
        if prior == "acknowledged":
            self.planner.store.runtime.state(self.planner.run_id, "running")
            self.stage("planner_continuation_running")
            return
        if prior is not None:
            raise ConsumerBlocked("planner_continuation_unknown_needs_readback")
        text = self.initial_prompts.read_continuation(self.ref("critic_output"))
        digest = hashlib.sha256(text.encode()).hexdigest()
        admission = self.initial_prompts.verify_continuation(self.ref("critic_output"), digest)
        # A per-prompt three-step limit is not a cumulative session budget when
        # continuing. Measured first-phase usage and the pinned bound must fit.
        if (
            not isinstance(admission, dict)
            or set(admission) != {"session_id", "prompt_digest", "observed_session_steps"}
            or admission["session_id"] != self.planner.binding["session_id"]
            or admission["prompt_digest"] != digest
            or type(admission["observed_session_steps"]) is not int
            or not 1 <= admission["observed_session_steps"] <= 2
            or admission["observed_session_steps"] + self.planner.supervisor.profile["max_steps"]
            > 3
        ):
            raise ConsumerBlocked("continuation_cumulative_step_admission_required")
        self.ref("continuation_step_admission", admission)
        message_id = (
            "msg_" + hashlib.sha256((self.id + "\ncritic_response").encode()).hexdigest()[:32]
        )
        self.ref("continuation_message_id", message_id)
        self.ref("continuation_prompt_digest", digest)
        self.planner.store.reference(
            self.planner.run_id,
            "continuation_prompt",
            {
                "message_id": message_id,
                "prompt_digest": digest,
            },
        )
        # Same durable session; never use the generic idempotent mutation replay
        # mechanism for a model prompt, including on a lost ACK.
        if not self.planner.store.runtime.begin(self.planner.run_id, boundary):
            raise ConsumerBlocked("planner_continuation_unknown_needs_readback")
        self.planner.fence()
        try:
            self.planner.supervisor.harness.prompt({**runtime, "message_id": message_id}, text)
        except Exception:
            self.planner.store.runtime.finish(self.planner.run_id, boundary, "uncertain")
            raise ConsumerBlocked("planner_continuation_unknown_needs_readback") from None
        self.planner.store.runtime.finish(self.planner.run_id, boundary, "acknowledged")
        self.planner.store.runtime.state(self.planner.run_id, "running")
        self.stage("planner_continuation_running")

    def reconcile_continuation(self, reader):
        """Authenticated exact session/message/digest readback, not a re-prompt."""
        self.planner.fence()
        expected = {
            "session_id": self.planner.binding["session_id"],
            "message_id": self.ref("continuation_message_id"),
            "prompt_digest": self.ref("continuation_prompt_digest"),
        }
        observed = reader.read_prompt_receipt(expected["session_id"], expected["message_id"])
        if observed != expected:
            raise ConsumerBlocked("planner_continuation_readback_unknown")
        self.planner.store.runtime.finish(
            self.planner.run_id, "planner_critic_response", "acknowledged"
        )
        self.planner.store.runtime.state(self.planner.run_id, "running")
        self.stage("planner_continuation_running")

    def _accepted(self, snapshot):
        proposal = self.planner.mcp.call(
            "tessera_read_proposal", {"proposal_id": self.ref("proposal_id")}
        )
        promotion = proposal.get("promotion")
        if (
            not isinstance(promotion, dict)
            or promotion.get("proposal_id") != self.ref("proposal_id")
            or not snapshot.get("review_id")
            or snapshot.get("approved_task_id") != promotion.get("task_id")
            or snapshot.get("review_subject_id") != self.ref("proposal_id")
        ):
            raise ConsumerBlocked("human_review_and_promotion_required")
        self.ref("review_id", snapshot["review_id"])
        self.ref("approved_task_id", snapshot["approved_task_id"])
        self.ref("promoted_proposal_id", self.ref("proposal_id"))

    def _consume(self, action, snapshot):
        self._accepted(snapshot)
        command = snapshot["commands"][action]
        if command["payload"]["command"]["action"] != "attempt:" + action:
            raise ConsumerBlocked("approved_command_action_changed")
        if action == "dispatch" and command["payload"]["command"].get("attempt_id") != self.ref(
            "attempt_id"
        ):
            raise ConsumerBlocked("approved_dispatch_attempt_changed")
        self.ref(action + "_command", command)
        return self.planner.consume_grant(command["grant_id"], command["payload"])

    def _observe_experiment(self, snapshot):
        command = snapshot["commands"]["status"]
        if command["payload"]["command"]["action"] != "attempt:status" or command["payload"][
            "command"
        ]["attempt_id"] != self.ref("attempt_id"):
            raise ConsumerBlocked("attempt_status_binding_changed")
        sequence = self.store.next_poll(self.id)
        if sequence > 64:
            raise ConsumerBlocked("attempt_poll_bound_reached")
        # A new persisted read poll key observes current state, not a cached ACK.
        result = self.planner.mcp.call(
            "tessera_consume_grant",
            {
                **command,
                "idempotency_key": f"research-status-{self.id}-{sequence}",
            },
        )
        status = self.output_pipeline.attempt_status(result, self.ref("attempt_id"))
        if status not in {
            "queued",
            "unknown",
            "prepared",
            "running",
            "cancel_requested",
            "succeeded",
            "failed",
            "canceled",
        }:
            raise ConsumerBlocked("attempt_status_unknown")
        if status in {"succeeded", "failed", "canceled"}:
            self.ref("experiment_terminal_status", status)
            self.stage("record_observation" if status == "succeeded" else status)

    def _cancel(self, snapshot, *, reconcile=False):
        command = snapshot["commands"]["cancel"]
        if command["payload"]["command"]["action"] != "execution:cancel":
            raise ConsumerBlocked("cancel_command_action_changed")
        self.ref("cancel_command", command)
        # Cancellation has its own issued command/fence and must remain possible
        # after reasoning expiry; the authenticated adapter verifies it separately.
        digest = hashlib.sha256(canonical(command).encode()).hexdigest()
        intent, fresh = self.store.begin(self.id, "cancel_experiment", digest)
        if intent["state"] == "acknowledged":
            self.ref("cancel_result", intent["result_id"])
            return
        if not fresh and not reconcile:
            raise ConsumerBlocked("cancel_ack_unknown_requires_exact_reconciliation")
        result = self.approvals.consume_cancel(
            self.id, command, self.ref("attempt_id"), intent["identity"]
        )
        if not isinstance(result, dict) or not result.get("id"):
            raise ConsumerBlocked("cancel_ack_unknown")
        self.ref("cancel_result", result["id"])
        self.store.acknowledged(self.id, "cancel_experiment", result["id"])

    def reconcile_cancel(self):
        """Explicit same-key typed API reconciliation, never automatic replay.

        Current issued authority is read again by the authenticated adapter; a
        changed command/grant cannot replace the held unknown request. Model
        prompts use separate read-only receipt reconciliation, never this path.
        """
        self._cancel(self._poll(), reconcile=True)
        self.stage("cancel_requested")

    def receipt(self):
        return {
            "journey_id": self.id,
            "stage": self.store.journey(self.id)["stage"],
            "planner_run": self.planner.run_id,
            "critic_run": self.critic.run_id,
            "model_understanding_verified": False,
            "provider_termination_verified": False,
        }

    def close(self):
        if hasattr(self, "resources"):
            resources = list(reversed(self.resources))
            self.resources = []
        else:
            resources = [
                resource
                for consumer in (self.planner, self.critic)
                for resource in (consumer.peer, consumer.collector, consumer.store)
            ]
        failed = False
        seen = set()
        for resource in resources:
            if resource is not None and id(resource) not in seen:
                seen.add(id(resource))
                try:
                    resource.close()
                except Exception:
                    failed = True
        if failed:
            raise ConsumerBlocked("research_journey_shutdown_failed") from None
