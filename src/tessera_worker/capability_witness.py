"""Independent witness wire contract and fail-closed raw-observation validators.

The trusted computing base includes the pinned observer daemons, their node/CNI
sensors and the collector. Workloads, brokers and operator evidence files are not
observers. HMAC proves channel custody, not correctness of a compromised sensor.
No validator treats API resource requests as kernel enforcement.
"""

