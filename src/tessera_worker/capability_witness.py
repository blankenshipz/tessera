class Cleanup(Frozen):
    resource: Resource
    preconditions: dict[str, str] = Field(min_length=2, max_length=2)
    delete_status: Literal[200, 202]
    readback: dict
    observed_at: str = Field(max_length=40)


class WitnessReport(Frozen):
    version: Literal[1] = 1
    source: Literal["independent-daemon", "fake"]
    request: Challenge
    request_digest: Digest
    witness: WitnessPin
    started_at: str = Field(max_length=40)
    completed_at: str = Field(max_length=40)
    monotonic_elapsed_ms: int = Field(ge=0, le=5000)
    state: Literal["observed", "unknown", "failed"]
    resources: tuple[Resource, ...] = Field(max_length=64)
    observations: dict = Field(max_length=128)
    probes: dict = Field(max_length=128)
    # Exact UID preconditioned cleanup records, never a label-selector delete.
    cleanup: tuple[Cleanup, ...] = Field(max_length=64)
    native: dict = Field(default_factory=dict, max_length=128)


def safe_payload(value, *, secrets=()):
    """Reject sensitive responses BEFORE retaining them; do not log validation inputs.

    Only fixture data belongs on this channel. Key-name filtering is defense in
    depth, not a claim to identify arbitrary secrets hidden in arbitrary strings.
    Known runtime credentials must also be supplied by the transport for rejection.
    """
    data = encoded(value)
    if len(data) > 2 * 1024 * 1024:
        raise CollectionError("malformed-response")
    if any(secret and secret in data for secret in secrets):
        raise CollectionError("malformed-response")
    if any(word in data.lower() for word in (b"bearer ", b"-----begin", b'"client-key-data":')):
        raise CollectionError("malformed-response")

    def visit(item):
        if isinstance(item, dict):
            if any(
                re.sub(r"[-_]", "", key).lower()
                in {
                    "token",
                    "password",
                    "authorization",
                    "privatekey",
                    "secret",
                    "secretvalue",
                    "stringdata",
                    "requestkey",
                    "reportkey",
                    "signingkey",
                }
                for key in item
            ):
                raise CollectionError("malformed-response")
            for child in item.values():
                visit(child)
        elif isinstance(item, list):
            for child in item:
                visit(child)

    visit(value)
    return data


def seal_report(report, key):
    if type(key) is not bytes or len(key) < 32:
        raise CollectionError("auth-denied")
    payload = safe_payload(report.model_dump(mode="json"), secrets=(key,))
    return {
        "payload": decode(payload),
        "digest": hashlib.sha256(payload).hexdigest(),
        "signature": hmac.new(key, DOMAIN + payload, "sha256").hexdigest(),
    }


def open_report(envelope, key):
    try:
        if set(envelope) != {"payload", "digest", "signature"} or len(key) < 32:
            raise ValueError
        payload = safe_payload(envelope["payload"], secrets=(key,))
        if hashlib.sha256(payload).hexdigest() != envelope["digest"] or not hmac.compare_digest(
            hmac.new(key, DOMAIN + payload, "sha256").hexdigest(), envelope["signature"]
        ):
            raise ValueError
        report = WitnessReport.model_validate_json(payload)
        if canonical(report) != payload:
            raise ValueError
        return report
    except Exception:
        raise CollectionError("auth-denied") from None


def exact(value, fields):
    if type(value) is not dict or set(value) != set(fields.split()):
        raise CollectionError("contradictory")


def require(condition):
    if not condition:
        raise CollectionError("contradictory")


def number(value, *, minimum=0, maximum=2**53):
    require(type(value) is int and minimum <= value <= maximum)
    return value


def validate_report(report, request, pin, plan, *, now, fake=False):
    """All four gates are mandatory. Unknown/crash/partial/late is never a pass."""
    require(
        report.request == request
        and report.request_digest == canonical_digest(request.model_dump(mode="json"))
    )
    require(report.witness == pin and report.request.kind == pin.kind)
    require(report.source == ("fake" if fake else "independent-daemon"))
    m = plan.activation
    require(
        pin.namespace not in {m.namespace, m.control_namespace}
        and pin.identity
        not in {
            m.dispatcher_identity,
            f"system:serviceaccount:{m.namespace}:{m.service_account}",
        }
    )
    start, finish = stamp(report.started_at), stamp(report.completed_at)
    if (
        not (
            stamp(m.issued_at)
            <= stamp(request.started_at)
            <= start
            <= finish
            <= now
            < stamp(request.deadline)
            <= stamp(m.expires_at)
        )
        or (now - start).total_seconds() > 5
    ):
        raise CollectionError("stale")
    require(abs((finish - start).total_seconds() * 1000 - report.monotonic_elapsed_ms) <= 250)
    if report.state != "observed":
        raise CollectionError("unavailable")
    if pin.target_digest is not None:
        from .capability_witness_native import validate_native

        validate_native(report, plan)
    require(bool(report.resources))
    require(len({r.uid for r in report.resources}) == len(report.resources))
    for resource in report.resources:
        require(resource.run_nonce == m.nonce)
        require(
            (resource.namespace, resource.namespace_uid)
            in {
                (m.namespace, m.namespace_uid),
                (pin.namespace, pin.namespace_uid),
            }
        )
        require(stamp(request.started_at) <= stamp(resource.created_at) <= finish)
        if resource.kind == "Pod":
            require(resource.node_uid == pin.node_uid)
            require(
                resource.identity is not None
                and resource.identity.startswith(f"system:serviceaccount:{resource.namespace}:")
            )
            require(resource.identity not in {pin.identity, m.dispatcher_identity})
    require({c.resource for c in report.cleanup} == set(report.resources))
    require(len(report.cleanup) == len(report.resources))
    for cleanup in report.cleanup:
        require(
            cleanup.preconditions
            == {
                "uid": cleanup.resource.uid,
                "resourceVersion": cleanup.resource.resource_version,
            }
        )
        require(cleanup.readback == {"kind": "Status", "code": 404, "reason": "NotFound"})
        require(start <= stamp(cleanup.observed_at) <= finish)
    # Legacy probes carry ancillary TLS/installer/RBAC observations as well. They
    # remain checked independently by RawEvidenceInspector, never synthesized here.
    require(set(report.probes) == set(request.inputs["probes"]))
    for key, probe in report.probes.items():
        exact(probe, "request response observed_at nonce subject")
        require(probe["request"] == request.inputs["probes"][key])
        require((probe["nonce"], probe["subject"]) == (m.nonce, plan.digest))
        require(start <= stamp(probe["observed_at"]) <= finish)
    {
        "cni": validate_cni,
        "quota": validate_quota,
        "watchdog": validate_watchdog,
        "admission": validate_admission,
    }[pin.kind](report, plan)


def validate_cni(report, plan):
    obs = report.observations
    exact(obs, "policy_uid policy_resource_version converged_at samples")
    require(bool(obs["policy_uid"]) and bool(obs["policy_resource_version"]))
    require(stamp(report.started_at) <= stamp(obs["converged_at"]) <= stamp(report.completed_at))
    samples = obs["samples"]
    classes = {
        "allowed",
        "allowed-dns",
        "public",
        "private",
        "metadata",
        "control",
        "dns-bypass",
        "proxy",
    }
    require(type(samples) is list and len(samples) == len(classes))
    require({s["class"] for s in samples} == classes)
    resources = {r.uid: r for r in report.resources}
    endpoints, identities, addresses, pods = set(), set(), set(), set()
    for s in samples:
        exact(
            s,
            "class pod_uid endpoint_uid identity address port protocol request response "
            "connect http_status dns_rcode cni policy_uid packets_sent packets_dropped "
            "proxy_environment proxy_used observed_at endpoint_challenge",
        )
        pod, endpoint = resources[s["pod_uid"]], resources[s["endpoint_uid"]]
        require(pod.kind == "Pod" and pod.namespace == plan.activation.namespace)
        require(pod.uid not in pods and pod.identity == s["identity"])
        pods.add(pod.uid)
        require(endpoint.kind in {"Pod", "Service", "EndpointSlice"})
        require(endpoint.namespace == report.witness.namespace)
        require(s["identity"] not in identities and s["identity"] != report.witness.identity)
        require(s["identity"].startswith(f"system:serviceaccount:{pod.namespace}:"))
        identities.add(s["identity"])
        require(s["endpoint_uid"] not in endpoints)
        endpoints.add(s["endpoint_uid"])
        address = ipaddress.ip_address(s["address"])
        require(str(address) == s["address"] and s["address"] not in addresses)
        addresses.add(s["address"])
        number(s["port"], minimum=1, maximum=65535)
        require(s["protocol"] in {"HTTP", "DNS"})
        require(s["protocol"] == ("DNS" if s["class"] in {"allowed-dns", "dns-bypass"} else "HTTP"))
        require(s["proxy_environment"] == [] and s["proxy_used"] is False)
        require(
            s["request"] == report.request.challenge
            and s["endpoint_challenge"] == report.request.challenge
        )
        require(s["policy_uid"] == obs["policy_uid"])
        require(stamp(obs["converged_at"]) <= stamp(s["observed_at"]) <= stamp(report.completed_at))
        sent = number(s["packets_sent"], minimum=1, maximum=8)
        number(s["packets_dropped"], maximum=8)
        if s["class"] in {"allowed", "allowed-dns"}:
            require(
                (
                    s["connect"],
                    s["http_status"],
                    s["response"],
                    s["cni"],
                    s["packets_dropped"],
                    s["dns_rcode"],
                )
                == (
                    "connected",
                    200 if s["class"] == "allowed" else None,
                    report.request.challenge,
                    "FORWARDED",
                    0,
                    None if s["class"] == "allowed" else 0,
                )
            )
        else:
            # A timeout alone, refusal, HTTP error/success or DNS NXDOMAIN is not
            # policy denial. Require correlated node-side DROP for every packet.
            require(
                (
                    s["connect"],
                    s["http_status"],
                    s["response"],
                    s["cni"],
                    s["packets_dropped"],
                    s["dns_rcode"],
                )
                == ("timeout", None, None, "DROP", sent, None)
            )


def validate_quota(report, plan):
    o, q = report.observations, plan.activation.quota
    exact(
        o,
        "pod_uid pvc_uid cgroup_version cgroup_id cpu_max memory_max pids_max "
        "cpu_stat_before cpu_stat_after memory_events_before memory_events_after "
        "pids_events_before pids_events_after memory_peak pids_peak termination events "
        "filesystems outside_workspace allocation_bytes fork_attempts limits_before",
    )
    require(o["pod_uid"] in {r.uid for r in report.resources if r.kind == "Pod"})
    require(
        next(r for r in report.resources if r.uid == o["pod_uid"]).namespace
        == plan.activation.namespace
    )
    require(o["pvc_uid"] == plan.activation.pvc_uid)
    require(o["cgroup_version"] == 2 and bool(o["cgroup_id"]))
    require(o["cpu_max"] == f"{q.cpu_millicores * 100} 100000")
    require(o["memory_max"] == q.memory_bytes and o["pids_max"] == plan.pids)
    require(
        o["limits_before"]
        == {
            k: o[k]
            for k in (
                "pod_uid",
                "pvc_uid",
                "cgroup_id",
                "cgroup_version",
                "cpu_max",
                "memory_max",
                "pids_max",
            )
        }
    )
    for before, after, counter in (
        ("cpu_stat_before", "cpu_stat_after", "nr_throttled"),
        ("memory_events_before", "memory_events_after", "oom_kill"),
        ("pids_events_before", "pids_events_after", "max"),
    ):
        exact(o[before], counter)
        exact(o[after], counter)
        require(number(o[after][counter]) > number(o[before][counter]))
    require(0 < number(o["memory_peak"]) <= q.memory_bytes)
    require(number(o["pids_peak"]) == plan.pids)
    require(q.memory_bytes < number(o["allocation_bytes"]) <= q.memory_bytes + 1024 * 1024)
    require(number(o["fork_attempts"]) == plan.pids + 1)
    require(o["termination"] == {"reason": "OOMKilled", "exit_code": 137, "restart_count": 0})
    require(o["events"] == [{"pod_uid": o["pod_uid"], "reason": "OOMKilled"}])
    fs = o["filesystems"]
    require(type(fs) is list and len(fs) == 3)
    limits = {
        "output-bytes": q.output_bytes,
        "output-inodes": q.output_inodes,
        "ephemeral-bytes": q.ephemeral_bytes,
    }
    require({item["resource"] for item in fs} == set(limits))
    for item in fs:
        exact(
            item,
            "resource mechanism mount_id project_id hard_limit usage_before usage_after "
            "attempted errno mount_pvc_uid",
        )
        limit = limits[item["resource"]]
        require(item["mechanism"] == "filesystem-project-quota")
        require(bool(item["mount_id"]) and number(item["project_id"], minimum=1) > 0)
        require(
            item["hard_limit"] == limit and item["usage_before"] == item["usage_after"] == limit
        )
        require(item["attempted"] == 1 and item["errno"] == "EDQUOT")
        require(
            item["mount_pvc_uid"]
            == (None if item["resource"].startswith("ephemeral") else o["pvc_uid"])
        )
    require(
        o["outside_workspace"]
        == {
            "root_write": "EROFS",
            "host_path": "ENOENT",
            "control_pvc": "ENOENT",
            "parent_escape": "EACCES",
            "symlink_escape": "EACCES",
            "ambient_token": "ENOENT",
        }
    )


def validate_watchdog(report, plan):
    o, m = report.observations, plan.activation
    exact(o, "watchdog_identity clock_boot_id cases")
    require(o["watchdog_identity"] == m.watchdog.identity == report.witness.identity)
    require(o["clock_boot_id"] == report.witness.boot_id)
    cases = o["cases"]
    require(type(cases) is list and len(cases) == 2)
    require({c["trigger"] for c in cases} == {"broker-suspended", "revoked"})
    uids = set()
    for c in cases:
        exact(
            c,
            "trigger pod_uid heartbeat_sequence heartbeat_challenge heartbeat_at "
            "trigger_at kill_at confirmed_at quiet_until process_exit cgroup_populated "
            "write_count_before write_count_after credential_state kill_requests",
        )
        require(c["pod_uid"] in {r.uid for r in report.resources if r.kind == "Pod"})
        require(c["pod_uid"] not in uids)
        uids.add(c["pod_uid"])
        require(
            c["heartbeat_sequence"] == 1 and c["heartbeat_challenge"] == report.request.challenge
        )
        hb, trigger, kill, confirmed, quiet = (
            stamp(c[k])
            for k in ("heartbeat_at", "trigger_at", "kill_at", "confirmed_at", "quiet_until")
        )
        require(
            stamp(report.started_at)
            <= hb
            <= trigger
            <= kill
            <= confirmed
            < quiet
            <= stamp(report.completed_at)
        )
        require((quiet - confirmed).total_seconds() >= m.watchdog.heartbeat_seconds)
        require(
            (confirmed - trigger).total_seconds()
            <= m.watchdog.lease_seconds + m.watchdog.kill_grace_seconds
        )
        if c["trigger"] == "broker-suspended":
            require((kill - hb).total_seconds() >= m.watchdog.lease_seconds)
        require(c["process_exit"] == 137 and c["cgroup_populated"] == 0)
        number(c["cgroup_populated"], maximum=0)
        require(number(c["write_count_before"], minimum=1) == number(c["write_count_after"]))
        require(c["credential_state"] == "revoked" and c["kill_requests"] == 1)


def validate_admission(report, plan):
    o = report.observations
    exact(o, "policies bindings dry_runs actual")
    policies = [x for x in plan.objects() if x["kind"] == "ValidatingAdmissionPolicy"]
    bindings = [x for x in plan.objects() if x["kind"] == "ValidatingAdmissionPolicyBinding"]
    for expected, observed in ((policies, o["policies"]), (bindings, o["bindings"])):
        require(len(expected) == len(observed))
        for want, got in zip(expected, observed, strict=True):
            require(raw_object(got) == want)
            meta = got["metadata"]
            require(
                bool(meta["uid"])
                and bool(meta["resourceVersion"])
                and number(meta["generation"], minimum=1) > 0
            )
            if want["kind"] == "ValidatingAdmissionPolicy":
                require(want["spec"]["failurePolicy"] == "Fail")
                require(
                    got["status"]
                    == {
                        "observedGeneration": meta["generation"],
                        "typeChecking": {"expressionWarnings": []},
                    }
                )
            else:
                require(want["spec"]["validationActions"] == ["Deny"])
    expected = {"positive": plan.job(), **negative_jobs(plan)}
    dry = o["dry_runs"]
    require(set(dry) == {f"{kind}:{key}" for kind in ("Job", "Pod") for key in expected})
    for kind in ("Job", "Pod"):
        for key, job in expected.items():
            obj = (
                job
                if kind == "Job"
                else {
                    "apiVersion": "v1",
                    "kind": "Pod",
                    "metadata": plan.metadata(plan.name),
                    "spec": job["spec"]["template"]["spec"],
                }
            )
            r = dry[f"{kind}:{key}"]
            exact(r, "request response status audit_id field_validation dry_run")
            require(
                r["request"] == obj and r["field_validation"] == "Strict" and r["dry_run"] == "All"
            )
            require(bool(r["audit_id"]))
            if key == "positive":
                require(r["status"] == 201 and raw_object(r["response"]) == obj)
            else:
                # Exact policy denial; RBAC/quota/schema failure is not admission proof.
                from .capability_inspection import RawEvidenceInspector

                require(
                    r["status"] == 403
                    and r["response"]
                    == RawEvidenceInspector.expected_response(plan, key, policy_uid="unused")
                )
    actual = o["actual"]
    require(type(actual) is list and len(actual) == 2)
    require({a["request"]["kind"] for a in actual} == {"Job", "Pod"})
    for a in actual:
        exact(a, "request response persisted status audit_id field_validation")
        obj = a["request"]
        kind = obj["kind"]
        require(obj == dry[f"{kind}:positive"]["request"])
        require(a["status"] == 201 and bool(a["audit_id"]) and a["field_validation"] == "Strict")
        for got in (a["response"], a["persisted"]):
            require(raw_object(got) == obj)
            require(bool(got["metadata"]["uid"]) and bool(got["metadata"]["resourceVersion"]))
            require(number(got["metadata"]["generation"], minimum=1) > 0)
        require(a["response"] == a["persisted"])
        resource = next(r for r in report.resources if r.kind == kind)
        if kind == "Pod":
            require(
                resource.identity
                == f"system:serviceaccount:{plan.activation.namespace}:"
                + plan.activation.service_account
            )
        meta = a["persisted"]["metadata"]
        require(
            (meta["uid"], meta["name"], meta["namespace"], meta["resourceVersion"])
            == (resource.uid, resource.name, resource.namespace, resource.resource_version)
        )
