"""A tiny synthetic public snapshot for the MCP steering smoke (ADR 0120, amendment).

``tessera dev smoke-credentials issue`` makes sure the project holds one snapshot whose bytes are
fixed, synthetic and declared public, so the steering smoke needs no human step. The bytes are the
constants below: nothing is read from the owner's data. The snapshot is adopted by the local owner
(with the ``smoke-credentials`` automation label, so the data-class record carries the decision
class ``owner_automation_labelled``) through the ordinary adoption path and its atomic public
declaration; nothing here lets an agent declare anything public.

The inventory digest includes the root path, so the digest is computed over a fixed logical root
(``LOGICAL_ROOT``) rather than the temporary directory the bytes are generated in. The result is
the same on every run and machine.
"""

from __future__ import annotations

import dataclasses
import os
import shutil
import sqlite3
import tempfile
from pathlib import Path
from typing import Any

from . import approval_trust
from .snapshots import SnapshotStore
from .store import Conflict, _connect
from .workspace import CapturedWorkspace, capture_workspace, inventory_digest

LABEL = "smoke-credentials"
LOGICAL_ROOT = "/tessera-smoke-synthetic-v1"
DATA_CLASS = {
    "data_class": "public",
    "license": "CC0-1.0",
    "source": "https://tessera.invalid/smoke-synthetic-v1",
}
REFUSAL = "smoke_snapshot_digest_not_public"

# Fixed, ASCII, clearly synthetic; sorted by name. Changing a byte changes the digest.
SMOKE_FILES: dict[str, bytes] = {
    "README.txt": (
        b"Synthetic smoke-test data for Tessera. Not real data. CC0-1.0.\n"
        b"Every value below is made up and carries no information.\n"
    ),
    "values.csv": b"id,value\n1,0.25\n2,0.50\n3,0.75\n",
}


def generate(directory: Path) -> None:
    """Write exactly ``SMOKE_FILES`` (files 0600) into an existing directory, made 0700."""
    directory = Path(directory)
    os.chmod(directory, 0o700)
    for name in sorted(SMOKE_FILES):
        descriptor = os.open(
            directory / name,
            os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0),
            0o600,
        )
        with os.fdopen(descriptor, "wb") as handle:
            handle.write(SMOKE_FILES[name])


def capture_synthetic(directory: Path | None = None) -> tuple[CapturedWorkspace, str]:
    """Capture the generated bytes under the fixed logical root. Returns (capture, digest).

    ``directory`` (empty, existing) is only where the bytes are written for the descriptor-safe
    capture; it never affects the digest. Without one, a private temporary directory is used.
    """
    scratch = None if directory is not None else Path(tempfile.mkdtemp(prefix="tessera-smoke-"))
    root = scratch if directory is None else Path(directory)
    try:
        generate(root)
        captured = capture_workspace(root)
    finally:
        if scratch is not None:
            shutil.rmtree(scratch, ignore_errors=True)
    inventory = dataclasses.replace(captured.inventory, root=LOGICAL_ROOT)
    captured = dataclasses.replace(captured, inventory=inventory)
    return captured, inventory_digest(inventory)


def _held(
    connection: sqlite3.Connection, org_id: str, project_id: str, digest: str
) -> tuple[str | None, bool]:
    """(a public snapshot of this project with the digest, whether any non-public one exists)."""
    from .data_class import PUBLIC, snapshot_data_class

    public_id, other = None, False
    for row in connection.execute(
        """SELECT s.id, s.project_id FROM source_snapshots s JOIN projects p ON p.id = s.project_id
        WHERE p.org_id = ? AND s.digest = ? ORDER BY s.created_at, s.id""",
        (org_id, digest),
    ).fetchall():
        if snapshot_data_class(connection, row["id"])["data_class"] == PUBLIC:
            if public_id is None and row["project_id"] == project_id:
                public_id = row["id"]
        else:
            other = True
    return public_id, other


def ensure_public_snapshot(
    state_dir: Path, owner: dict[str, Any], project_id: str
) -> dict[str, Any]:
    """Reuse the project's synthetic public snapshot or adopt it; ``created`` says which.

    ``owner`` is the root owner's authenticated actor. Raises a closed ``Conflict`` when the
    same bytes are already held as anything but public (that cannot be corrected).
    """
    capture, digest = capture_synthetic()
    store = SnapshotStore(Path(state_dir).expanduser())
    connection = _connect(store.database_path)
    try:
        existing, non_public = _held(connection, owner["org_id"], project_id, digest)
    finally:
        connection.close()
    if existing is not None:
        return {"snapshot_id": existing, "digest": digest, "created": False}
    if non_public:
        raise Conflict(
            f"{REFUSAL}: these synthetic bytes are already held as a non-public snapshot; "
            "that classification cannot be changed, so no smoke snapshot was created."
        )
    actor = dict(owner)
    actor[approval_trust.AUTOMATION_KEY] = LABEL
    _status, adopted = store.adopt_snapshot(
        actor,
        project_id,
        "smoke-snapshot-v1-" + digest,
        digest,
        capture,
        data_class=dict(DATA_CLASS),
    )
    return {"snapshot_id": adopted["id"], "digest": digest, "created": True}
